async def test_song_goes_out_as_audio_with_post_delivery_actions(
    bot: Bot, session: RecordingSession, kit: Kit
) -> None:
    """The song goes out with sendAudio, carrying title, caption, watermark, and action buttons."""
    # Arrange / Act
    result = await deliver(bot, kit)

    # Assert
    assert isinstance(result, Ok)
    audio = session.last_named("SendAudio")
    assert audio.title == kit.lyrics.title
    assert UZBEK_NAME_CANONICAL in (audio.caption or "")
    assert watermark("watermark.song") in (audio.caption or "")

    # Post-delivery actions are attached directly to the song message
    payloads = {data for _text, data in buttons(audio.reply_markup)}
    assert NavCB(action=NavAction.MAKE_ANOTHER).pack() in payloads
    assert SupportCB(action=SupportAction.OPEN, ref=pack_reference(kit.order_id)).pack() in payloads


