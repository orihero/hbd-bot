async def deliver(bot: Bot, kit: Kit, **overrides: object) -> object:
    return await deliver_kit(bot, chat_id=CHAT_ID, kit=kit, language=Language.EN, **overrides)  # type: ignore[arg-type]


def watermark(key: str, language: Language = Language.EN) -> str:
    """The rendered watermark line, read the way delivery reads it."""
    return translate(key, language, handle=WATERMARK_HANDLE)


def fail_once(session: RecordingSession, method: str, error: Exception) -> None:
    """Arm ``method`` to be rejected exactly once, then let the next attempt through."""
    session.failures[method] = error
    original = session.make_request

    async def once(
        bot: Bot,
        request: TelegramMethod[Any],
        timeout: int | None = None,  # noqa: ASYNC109 - aiogram signature
    ) -> Any:
        try:
            return await original(bot, request, timeout)
        finally:
            session.failures.pop(type(request).__name__, None)

    session.make_request = once  # type: ignore[assignment,method-assign]


async def test_exactly_two_messages_delivered_in_order(
    bot: Bot, session: RecordingSession, kit: Kit
) -> None:
    """Delivery sends exactly two messages: lyric image (SendPhoto) then the song (SendAudio)."""
    # Arrange / Act
    result = await deliver(bot, kit)

    # Assert
    assert isinstance(result, Ok)
    assert len(session.calls) == 2
    assert session.call_names == ("SendPhoto", "SendAudio")
    assert not session.named("SendVoice")
    assert not session.named("SendMessage")


async def test_lyric_image_is_generated_and_sent_as_photo(
    bot: Bot, session: RecordingSession, kit: Kit
) -> None:
    """The lyric image is auto-generated on disk and sent as a photo."""
    # Arrange — ensure no pre-existing image
    image_path = kit.song.path.parent / LYRICS_IMAGE_FILENAME
    if image_path.exists():
        image_path.unlink()

    # Act
    result = await deliver(bot, kit)

    # Assert
    assert isinstance(result, Ok)
    assert image_path.exists()
    assert image_path.stat().st_size > 0
    photo = session.last_named("SendPhoto")
    assert photo is not None


async def test_lyric_image_rendered_with_orange_background_when_google_flow(
    bot: Bot, session: RecordingSession, kit: Kit
) -> None:
    """If music was generated by Google flow, lyrics image background is orange."""
    gemini_song = kit.song.model_copy(update={"provider": "gemini_music"})
    gemini_kit = kit.model_copy(update={"song": gemini_song})
    image_path = gemini_kit.song.path.parent / LYRICS_IMAGE_FILENAME
    if image_path.exists():
        image_path.unlink()

    result = await deliver(bot, gemini_kit)

    assert isinstance(result, Ok)
    assert image_path.exists()
    from PIL import Image

    with Image.open(image_path) as img:
        top_pixel = img.getpixel((0, 0))
        assert top_pixel == (220, 90, 20)


