"""Delivery: exactly two messages — lyric card image, then the song itself.

Two rules, each of which is a product requirement:
1. When music is generated, send exactly 2 messages (remove all other messages):
   a) Image with lyrics of the song (auto-generated locally via Pillow);
   b) Generated song itself (with audio player, caption, watermark, and post-delivery actions).
2. All other delivery messages (greetings voice notes, text lyric sheets, separate closing messages)
   are removed from the delivery flow.
"""

